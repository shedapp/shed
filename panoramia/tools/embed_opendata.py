#!/usr/bin/env python3
"""Embed the curated AKUDENTAL subset into src/66-opendata-data.js.

Usage: python3 tools/embed_opendata.py <curated-dir>          (AKUDENTAL, output dir of curate_akudental.py)
       python3 tools/embed_opendata.py <curated-dir> --opg    (DentalOPG-1550, output dir of curate_dentalopg.py)
"""
import base64, json, os, sys

def main():
    src = sys.argv[1]
    opg = '--opg' in sys.argv
    here = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    m = json.load(open(os.path.join(src, 'subset_manifest.json'), encoding='utf-8'))
    images = []
    for e in m['images']:
        with open(os.path.join(src, 'subset', e['file']), 'rb') as fh:
            b64 = base64.b64encode(fh.read()).decode('ascii')
        images.append(dict(e, data=b64))
    meta = {k: v for k, v in m.items() if k != 'images'}
    payload = json.dumps(dict(meta, images=images), ensure_ascii=False, separators=(',', ':'))
    if opg:
        out = ('/* PanoramIA — embedded open dataset subset. GENERATED by tools/embed_opendata.py --opg; do not edit by hand.\n'
               '   Dataset: DentalOPG-1550 (Chowdhury & Arman, Mendeley Data V3, doi:10.17632/rtt726b26d.3), CC BY 4.0.\n'
               '   Images are 8-bit grayscale JPEG, 1000 px wide; coordinates are in that pixel space. FDI numbers are estimated by position. */\n'
               '(function (root) { root.PX_OPENDATA_SUBSET_OPG = ' + payload + '; })(typeof window !== \'undefined\' ? window : globalThis);\n')
        path = os.path.join(here, 'src', '66-opendata-opg-data.js')
    else:
        out = ('/* PanoramIA — embedded open dataset subset. GENERATED by tools/embed_opendata.py; do not edit by hand.\n'
               '   Dataset: AKUDENTAL (Öz et al., BMC Oral Health 2026, doi:10.1186/s12903-025-07645-0), CC BY-NC-SA 4.0.\n'
               '   Images are 8-bit grayscale JPEG, 1400 px wide; coordinates are in that pixel space. */\n'
               '(function (root) { root.PX_OPENDATA_SUBSET = ' + payload + '; })(typeof window !== \'undefined\' ? window : globalThis);\n')
        path = os.path.join(here, 'src', '66-opendata-data.js')
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(out)
    print('wrote', path, round(len(out.encode('utf-8')) / 1e6, 2), 'MB;', len(images), 'images')

if __name__ == '__main__':
    main()
